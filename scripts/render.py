def render_deck():
    deck = json.load(open("deck.json", encoding="utf-8"))
    entries, budget, basics = deck["deck"], deck["budget"], deck.get("basics", {})
    by_pkg = {}
    for c in entries:
        by_pkg.setdefault(c["package"], []).append(c)
    out = []
    for pkg in sorted(by_pkg):
        b = budget[pkg]
        out.append(f"\n### {pkg} — {len(by_pkg[pkg])} slots"
                   f"{' (flex)' if b.get('flex') else ''}")
        out.append(f"*Membership criterion:* {b['criterion']}")
        out.append(f"\n{deck['package_notes'][pkg]}\n")
        out.append("| Card | Cost | Type | Mode | Also | Answers | Beat | Note |")
        out.append("|---|---|---|---|---|---|---|---|")
        for c in sorted(by_pkg[pkg], key=lambda x: (x.get("cmc", 0), x["name"])):
            out.append("| {} | {} | {} | {} | {} | {} | {} | {} |".format(
                c["name"], c["mana_cost"] or "—", c["type_line"],
                c.get("mode_taken", "—"),
                ", ".join(c.get("roles_secondary", [])) or "—",
                ", ".join(c["refs"]), c.get("beat") or "—", c.get("note", "")))
    out.append("\n### basics\n" + ", ".join(f"{n}× {b}"
                                            for b, n in sorted(basics.items()) if n))
    out.append("\n### bench (lost its slot, ranked runner-up)\n")
    out.append("| Card | Package | Lost to | Why |")
    out.append("|---|---|---|---|")
    for b in sorted(deck.get("bench", []), key=lambda x: x["package"]):
        out.append(f"| {b['name']} | {b['package']} | {b['lost_to']} | {b['reason']} |")
    return "\n".join(out)


def render_import():
    deck = json.load(open("deck.json", encoding="utf-8"))
    out = [f"1 {deck['commander']}   # COMMANDER"]
    for c in sorted(deck["deck"], key=lambda x: x["name"]):
        out.append(f"1 {c['name']}")
    for b, n in sorted(deck.get("basics", {}).items()):
        if n:
            out.append(f"{n} {b}")
    return "\n".join(out)


if __name__ == "__main__":
    arg = sys.argv[1] if sys.argv[1:] else "deck"
    if arg == "strategy":
        print(render_strategy(json.load(open("strategy.json", encoding="utf-8"))))
    elif arg == "import":
        print(render_import())
    else:
        print(render_deck())
