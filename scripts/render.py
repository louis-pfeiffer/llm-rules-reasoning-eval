"""render.py (v8) -- prints artifacts. Never type a deliverable by hand.

  python render.py             decklist grouped by package, as markdown
  python render.py import      plain-text import list for a deckbuilding site
  python render.py strategy    strategy.md, rendered from strategy.json

v7 -> v8: strategy.md stops being authored in parallel with strategy.json and
becomes a rendering of it. Everything a reader sees is therefore inside the
object the validator checks. render_strategy() is importable so
validate_strategy.py can diff the rendered text against the file on disk and
fail the build if the two have drifted.
"""
import json
import re
import sys

CARDREF = re.compile(r"\[\[([^\]]+)\]\]")


def plain(s):
    """Strip [[Card Name]] markers for display."""
    return CARDREF.sub(lambda m: m.group(1), str(s))


def _wnum(x):
    d = re.sub(r"\D", "", x)
    return int(d) if d else 0


# --------------------------------------------------------------------------
# strategy.md
# --------------------------------------------------------------------------
def render_strategy(S):
    o = []
    w = o.append
    m = S.get("meta", {})

    w(f"# strategy.md — {m.get('commander', '?')} under {m.get('restriction', '?')}")
    w(f"{m.get('turn', 'Turn 1')}. Prompt {m.get('prompt_version', '?')}. "
      f"Date {m.get('date', '?')}.")
    w("")
    w("> Generated by `python render.py strategy` from `strategy.json`. "
      "Do not edit this file; edit the artifact and re-render.")

    if S.get("changelog"):
        w("\n## Changelog")
        for c in S["changelog"]:
            w(f"- **{c['date']}** — {plain(c['entry'])}")

    if S.get("assumptions"):
        w("\n## Assumptions")
        w("| # | Assumption | Why | What changes if it is wrong |")
        w("|---|---|---|---|")
        for a in S["assumptions"]:
            w(f"| {a['id']} | {plain(a['assumption'])} | {plain(a['why'])} "
              f"| {plain(a['if_wrong'])} |")

    if S.get("deck_phases"):
        w("\n## Deck phases used for per-phase scoring")
        for p in S["deck_phases"]:
            w(f"- **{p['id']} ({p['span']})** — {plain(p['note'])}")

    cap = S.get("captured_output", {})
    if cap.get("census"):
        w("\n## Census (raw output of config.census)")
        w("```\n" + cap["census"].rstrip() + "\n```")
    if S.get("census_note"):
        w("")
        w(plain(S["census_note"]))

    if S.get("rows"):
        w("\n## Phase 0 table with 0b verdicts")
        w("| id | dir | verdict | claim | pool hits | contradicts |")
        w("|---|---|---|---|---|---|")
        for r in S["rows"]:
            c = r["contradicts"]
            w("| {} | {} | **{}** | {} | {} — {} | `{}` → {}. {} |".format(
                r["id"], r["direction"], r["verdict"], plain(r["claim"]),
                r["pool_hit_count"], ", ".join(r["pool_hits"]) or "(none)",
                c["query"]["pattern"], ", ".join(c["cards"]) or "none found",
                plain(c["note"])))

    refs = [(r["id"], k, v) for r in S.get("rows", [])
            for k, v in (r.get("referents") or {}).items()]
    if refs:
        w("\n## Pronoun referent enumerations (P8)")
        for rid, card, note in refs:
            w(f"- **{card}** ({rid}): {plain(note)}")

    if S.get("rules_claims"):
        w("\n## Rules claims, quoted verbatim (§3.3)")
        w("| rule | claim | verbatim quote |")
        w("|---|---|---|")
        for c in S["rules_claims"]:
            w(f"| {c['rule']} | {plain(c['claim'])} | {c['quote']} |")

    if S.get("kill_chain"):
        w("\n## Kill chain (§1.4)")
        w("| # | link | pool support | example cards |")
        w("|---|---|---|---|")
        for i, l in enumerate(S["kill_chain"], 1):
            w(f"| K{i} | {plain(l['link'])} | {l['pool_count']} "
              f"| {', '.join(l.get('cards', []))} |")

    if S.get("weaknesses"):
        w("\n## Weaknesses and the answers searched for them")
        w("| id | weakness | answer searched in pool |")
        w("|---|---|---|")
        for k in sorted(S["weaknesses"], key=_wnum):
            a = S.get("weakness_answers", {}).get(k, {})
            w(f"| {k} | {plain(S['weaknesses'][k])} | "
              f"{', '.join(a.get('cards', [])) or '**none found**'} — "
              f"{plain(a.get('note', ''))} |")

    if S.get("play_lines"):
        w("\n## Play lines")
        for k in sorted(S["play_lines"], key=_wnum):
            w(f"- **{k}** — {plain(S['play_lines'][k])}")

    for key, title in (("opponent_model", "§6 opponent model — raw output"),
                       ("kill_math", "§1.4 kill math — raw output"),
                       ("validator", "Validator — raw stdout")):
        if cap.get(key):
            w(f"\n## {title}")
            w("```\n" + cap[key].rstrip() + "\n```")

    for section in S.get("prose", []):
        w(f"\n## {section['title']}")
        w(plain(section["body"]).strip())

    if S.get("prose_absolutes"):
        w("\n## Absolute quantifiers used in prose, with the query that would falsify each (P7)")
        w("| where | sentence | falsifying query | returned |")
        w("|---|---|---|---|")
        for a in S["prose_absolutes"]:
            q = a["falsifying_query"]
            w(f"| {a.get('where', '—')} | {plain(a['quote'])} "
              f"| `{q['field']}` ~ `{q['pattern']}` | empty |")

    if S.get("declined"):
        w("\n## Declined sub-tasks (§7.1)")
        for d in S["declined"]:
            w(f"- **{plain(d['task'])}** — {plain(d['why'])} "
              f"Would pay if: {plain(d['would_pay_if'])} "
              f"Did instead: {plain(d['did_instead'])}")

    w("\n## Manifest")
    w(", ".join(f"`{f}`" for f in S.get("manifest", [])))
    w("")
    return "\n".join(o)


